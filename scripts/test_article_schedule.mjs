import assert from 'node:assert/strict';
import {validateRecord} from '../supabase/functions/obcane-admin/rules.mjs';
import {pragueInput,pragueInstant,postStateLabel} from '../assets/article-schedule.js';
const article={title:'Připravená zpráva',slug:'pripravena-zprava',category:'original',author:'Redakce',body:'Ověřený obsah článku.',status:'scheduled',published_at:new Date(Date.now()+31*86400000).toISOString()};
assert.equal(validateRecord('posts',article).status,'scheduled');
assert.throws(()=>validateRecord('posts',{...article,body:''}));
assert.throws(()=>validateRecord('posts',{...article,published_at:null}));
assert.throws(()=>validateRecord('posts',{...article,published_at:'invalid'}));
assert.throws(()=>validateRecord('posts',{...article,published_at:new Date(Date.now()-60000).toISOString()}),/budoucnosti/);
assert.throws(()=>validateRecord('posts',{...article,status:'published'}),/Naplánovat/);
assert.equal(validateRecord('posts',{...article,status:'draft',body:''}).status,'draft');
assert.equal(validateRecord('posts',{...article,status:'published',published_at:new Date(Date.now()-60000).toISOString()}).status,'published');
assert.throws(()=>validateRecord('posts',{...article,category:'media'}));
assert.equal(validateRecord('posts',{...article,category:'media',source_url:'https://example.org/news',source_name:'Zdroj',source_date:'2026-11-01'}).category,'media');
assert.throws(()=>validateRecord('events',{...article,starts_at:article.published_at}));
assert.throws(()=>validateRecord('finances',{...article,year:2026}));
assert.equal(pragueInput('2026-12-14T08:00:00Z'),'2026-12-14T09:00');
assert.equal(pragueInstant('2026-12-14T09:00'),'2026-12-14T08:00:00.000Z');
assert.equal(pragueInstant('2027-07-14T09:00'),'2027-07-14T07:00:00.000Z');
assert.throws(()=>pragueInstant('2027-03-28T02:30'),/neexistuje/);
assert.throws(()=>pragueInstant('2027-10-31T02:30'),/dvakrát/);
assert.throws(()=>pragueInstant('2027-02-30T12:00'));
assert.throws(()=>pragueInstant('2027-01-01T25:00'));
assert.throws(()=>pragueInstant(''));
assert.equal(postStateLabel('scheduled'),'Naplánováno');
console.log('PASS: scheduling a month ahead, incomplete/past/invalid rejection, draft cancellation, immediate publication, unchanged event/finance statuses, Prague winter/summer time and both DST transitions');
