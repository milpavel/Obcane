-- Import storage only; does not change permissions on existing application tables.
create schema if not exists obcane;
create table if not exists obcane.sources (
 source_key text primary key, source_url text not null,
 checked_at timestamptz, status text not null default 'pending' check (status in ('pending','ok','error')),
 last_error text, updated_at timestamptz default now(), last_success_at timestamptz,
 item_count integer not null default 0
);
create table if not exists obcane.items (
 id bigint generated by default as identity primary key,
 source_key text not null references obcane.sources(source_key),
 external_url text not null, title text not null, category text,
 event_date date, published_at timestamptz, summary text,
 payload jsonb not null default '{}'::jsonb, last_seen_at timestamptz default now(),
 unique(source_key,external_url)
);
alter table obcane.sources add column if not exists last_success_at timestamptz;
alter table obcane.sources add column if not exists item_count integer not null default 0;
create table if not exists obcane.import_control (
 id boolean primary key default true check(id), token_hash text not null, lease_until timestamptz
);
alter table obcane.sources enable row level security;
alter table obcane.items enable row level security;
alter table obcane.import_control enable row level security;
create index if not exists obcane_items_published_idx on obcane.items(published_at desc);
